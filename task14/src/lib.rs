
//! # My Awesome Crate
//!
//! Эта библиотека предоставляет утилиты для работы с числами.


/// Складывает два числа.
///
/// # Examples
///
/// ```
/// let arg = 5;
/// let result = task14::add(2, 3);
/// assert_eq!(result, 5);
/// ```
///
/// # Panics
/// Эта функция не паникует.
///
/// # Errors
/// Функция не возвращает ошибок.
pub fn add(a: i32, b: i32) -> i32 {
    a + b
}